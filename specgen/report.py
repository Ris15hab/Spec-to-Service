"""runs/ -> results/summary.md + summary.json (+ optional README results block).

Why: every number in any doc must be regenerable from files. This module reads only
runs/*/**/result.json and meta.json; it never calls a model and has no timestamps, so
rerunning it on the same runs gives byte-identical output.
Mock-model runs are reported in a separate, clearly labeled table (plumbing only).
Deliberately does not: plot, smooth, or drop failed runs.
"""
import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path

RUNS, RESULTS = Path("runs"), Path("results")
BEGIN, END = "<!-- RESULTS:BEGIN (generated by `specgen report --update-readme`; do not edit) -->", "<!-- RESULTS:END -->"


def load(run_ids):
    dirs = [RUNS / r for r in run_ids] if run_ids else sorted(p for p in RUNS.iterdir() if p.is_dir() and not p.name.startswith("_"))
    results, metas = [], []
    for d in dirs:
        if (d / "meta.json").exists():
            metas.append(json.loads((d / "meta.json").read_text()))
        for f in sorted(d.glob("*/*/t*/result.json")):
            r = json.loads(f.read_text())
            r["run_id"], r["dir"] = d.name, str(f.parent)
            results.append(r)
    results.sort(key=lambda r: (r["model"], r["split"], r["spec"], r.get("trial", 1), r["run_id"]))
    return results, metas


def mean(xs):
    return round(sum(xs) / len(xs), 2) if xs else 0.0


def pct(n, d):
    return round(100 * n / d, 1) if d else 0.0


def aggregate(rs):
    n = len(rs)
    by_trial = defaultdict(list)
    for r in rs:
        by_trial[r.get("trial", 1)].append(r)
    rates = [pct(sum(x["pass_at_1"] for x in v), len(v)) for _, v in sorted(by_trial.items())]
    return {
        "n_runs": n, "pass_at_1_pct": pct(sum(r["pass_at_1"] for r in rs), n),
        "final_pass_pct": pct(sum(r["final_pass"] for r in rs), n),
        "mean_repairs": mean([r["repairs_used"] for r in rs]),
        "mean_tokens": mean([r["tokens_in"] + r["tokens_out"] for r in rs]),
        "mean_wall_s": mean([r["wall_time_s"] for r in rs]),
        "trials": len(by_trial), "pass_at_1_per_trial_range": [min(rates), max(rates)] if rates else None,
    }


def build(results, metas):
    real = [r for r in results if not r["mock"]]
    summary = {"n_runs_total": len(results), "n_real": len(real), "runs": sorted({m["run_id"] for m in metas}),
               "caching": sorted({str(m["cache"]) for m in metas}),
               "autoformat": sorted({"yes" if m.get("autoformat") else "no" for m in metas}), "fingerprints": sorted({m["fingerprint"] for m in metas}),
               "tables": {}, "mock_tables": {}, "first_failure": {}, "per_spec": {}, "skipped": {}}
    for label, pool, key in (("real", real, "tables"), ("mock", [r for r in results if r["mock"]], "mock_tables")):
        for split in ("dev", "heldout"):
            for model in sorted({r["model"] for r in pool}):
                rs = [r for r in pool if r["model"] == model and r["split"] == split]
                if rs:
                    summary[key][f"{model}|{split}"] = aggregate(rs)
    for model in sorted({r["model"] for r in real}):
        c = Counter(r["first_failure_category"] for r in real if r["model"] == model and not r["pass_at_1"])
        summary["first_failure"][model] = dict(sorted(c.items()))
        fin = Counter(r["final_failure_category"] for r in real if r["model"] == model and not r["final_pass"])
        summary["first_failure"][model + " (unrepaired final)"] = dict(sorted(fin.items()))
    for r in real:
        cell = summary["per_spec"].setdefault(r["spec"], {"split": r["split"], "models": {}})["models"].setdefault(r["model"], [0, 0, 0])
        cell[0] += 1
        cell[1] += r["pass_at_1"]
        cell[2] += r["final_pass"]
    sk = Counter(s for r in real for s in r["skipped"])
    summary["skipped"] = dict(sorted(sk.items()))
    return summary


def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    return "\n".join(out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def main_table(s, key, split):
    rows = []
    for k, a in s[key].items():
        model, sp = k.split("|")
        if sp == split:
            rng = f"{a['pass_at_1_per_trial_range'][0]}–{a['pass_at_1_per_trial_range'][1]}" if a["trials"] > 1 else "n/a (1 trial)"
            rows.append([model, a["n_runs"], f"{a['pass_at_1_pct']}%", f"{a['final_pass_pct']}%", a["mean_repairs"],
                         int(a["mean_tokens"]), a["mean_wall_s"], rng])
    return table(rows, ["model", "runs", "pass@1", "pass after repair (≤3)", "mean repairs", "mean tokens", "mean time (s)", "pass@1 range over trials (%)"]) if rows else "_no runs_"


def traces(real):
    """2-3 repaired runs and up to 2 unrepaired failures, as stage/category chains."""
    def chain(r):
        steps = [f"attempt {a['n']}: " + (f"{a['failed_stage']}/{a['category']}" if not a["ok"] else "PASS")
                 + (f" ({a['note']})" if a.get("note") else "") for a in r["attempts"]]
        return " → ".join(steps)
    fixed = [r for r in real if r["final_pass"] and not r["pass_at_1"]]
    lost = [r for r in real if not r["final_pass"]]
    out = []
    for title, pool in (("Fixed by the repair loop", fixed[:3]), ("Not fixed within 3 repairs", lost[:2])):
        out.append(f"**{title}**\n")
        out += [f"- `{r['model']}` / `{r['spec']}` ({r['split']}, trial {r.get('trial', 1)}): {chain(r)}  \n  trace: `{r['dir']}/calls.jsonl`" for r in pool] or ["- none"]
        out.append("")
    return "\n".join(out)


def render(s, results):
    real = [r for r in results if not r["mock"]]
    L = ["# Results (generated by `specgen report`; do not edit)", ""]
    L.append(f"Runs included: {', '.join(s['runs']) or 'none'} · real-model runs: {s['n_real']} · mock runs: {s['n_runs_total'] - s['n_real']} · "
             f"gofmt autoformat applied to model code: {', '.join(s['autoformat']) or 'no (older runs)'} · "
             f"response cache on: {', '.join(s['caching']) or 'n/a'} · prompt/repair code fingerprints: {', '.join(s['fingerprints']) or 'n/a'}")
    L += ["", "## Dev set (used while tuning prompts)", "", main_table(s, "tables", "dev"),
          "", "## Held-out set (frozen before the first eval; never tuned on)", "", main_table(s, "tables", "heldout")]
    if s["mock_tables"]:
        L += ["", "## MOCK model runs (plumbing tests only; says nothing about real models)", "", main_table(s, "mock_tables", "dev"), "", main_table(s, "mock_tables", "heldout")]
    L += ["", "## First-failure categories per model (runs that did not pass at attempt 0)", ""]
    cats = sorted({c for v in s["first_failure"].values() for c in v})
    L.append(table([[m] + [v.get(c, 0) for c in cats] for m, v in s["first_failure"].items()], ["model"] + cats) if cats else "_no failures_")
    models = sorted({r["model"] for r in real})
    L += ["", "## Per-spec matrix (pass@1 / final pass, as passes out of runs)", ""]
    rows = [[f"{sp} ({d['split']})"] + [("/".join(map(str, [d['models'][m][1], d['models'][m][2]])) + f" of {d['models'][m][0]}") if m in d["models"] else "–" for m in models]
            for sp, d in sorted(s["per_spec"].items())]
    L.append(table(rows, ["spec"] + models) if rows else "_no real-model runs_")
    L += ["", "## What the repair loop fixed vs. could not", "", traces(real)]
    L += ["## Skipped checks", "", (", ".join(f"`{k}` (in {v} runs)" for k, v in s["skipped"].items()) or "none"),
          "", "Skipped means the tool was not installed; those checks were NOT counted as passed.", "",
          "## Limitations", "",
          "- Small n: 15 specs, 1–3 trials per spec per model; differences of a few points are noise.",
          "- Free-tier / hosted models only unless a `local` model appears in the tables above (it is untested otherwise).",
          "- The verifier is my own: probes check status codes and metric names, not response bodies, so a pass is not proof of full correctness.",
          "- Endpoints with path parameters may legitimately 404, so a missing route there is only caught by spec `probes` or generated tests.",
          "- Dev specs were used to tune prompts; held-out specs were frozen first and not tuned on. Both sets were written by me, not sampled from real workloads.",
          "- Generated code runs unsandboxed on the host (timeouts and process-group kill only).",
          "- Not tested here: docker build, hadolint, kubeconform, any real cluster, self-hosted models."]
    return "\n".join(L) + "\n"


def update_readme(summary_md):
    p = Path("README.md")
    text = p.read_text() if p.exists() else ""
    block = f"{BEGIN}\n{summary_md}\n{END}"
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        text += "\n" + block + "\n"
    p.write_text(text)


def cli(cmd, rest, console):
    ap = argparse.ArgumentParser(prog="specgen report")
    ap.add_argument("--run-id", action="append", help="repeatable; default: every run in runs/")
    ap.add_argument("--update-readme", action="store_true")
    a = ap.parse_args(rest)
    results, metas = load(a.run_id)
    s = build(results, metas)
    md = render(s, results)
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "summary.json").write_text(json.dumps(s, indent=2, sort_keys=True) + "\n")
    (RESULTS / "summary.md").write_text(md)
    if a.update_readme:
        update_readme(md.replace("# Results (generated by `specgen report`; do not edit)", "## Results (generated)"))
    console.print(f"wrote results/summary.md and results/summary.json from {len(results)} runs")
    return 0
